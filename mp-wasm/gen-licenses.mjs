#!/usr/bin/env node
// Write the third-party license notices for the crates compiled into
// mp_wasm_bg.wasm. The browser bundle ships that binary, and MIT/BSD/Apache
// require their copyright and license texts to accompany distributed copies.
//
//   node mp-wasm/gen-licenses.mjs <out-file>
//
// Crate set: wasm32-unknown-unknown NORMAL dependencies of mp-wasm, resolved
// from mp-wasm/Cargo.lock (`cargo metadata --locked`). Proc-macro crates and
// build dependencies run on the build host only and are not linked into the
// .wasm, so they are not walked. Path (workspace) crates are this project's own
// AGPL-3.0 code and are skipped, but their dependencies are walked. Output is
// deterministic (no timestamps or local paths) so a rebuild is diffable.
import { execFileSync } from 'node:child_process'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const out = process.argv[2]
if (!out) {
  console.error('usage: node mp-wasm/gen-licenses.mjs <out-file>')
  process.exit(2)
}

const here = dirname(fileURLToPath(import.meta.url))
const metadata = JSON.parse(
  execFileSync(
    'cargo',
    [
      'metadata',
      '--format-version=1',
      '--locked',
      '--filter-platform=wasm32-unknown-unknown',
      `--manifest-path=${join(here, 'Cargo.toml')}`,
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ),
)

const packages = new Map(metadata.packages.map((p) => [p.id, p]))
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]))
const isProcMacro = (p) => p.targets.some((t) => t.kind.includes('proc-macro'))

const linked = new Set()
const queue = [metadata.resolve.root]
while (queue.length > 0) {
  const id = queue.pop()
  if (linked.has(id)) continue
  linked.add(id)
  for (const dep of nodes.get(id).deps) {
    const normal = dep.dep_kinds.some((k) => k.kind === null)
    if (normal && !isProcMacro(packages.get(dep.pkg))) queue.push(dep.pkg)
  }
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)/i
// Many crates ship byte-identical texts (chiefly the Apache-2.0 boilerplate);
// print each distinct text once and point later crates at its first holder.
const firstHolder = new Map()
const sections = [...linked]
  .map((id) => packages.get(id))
  .filter((p) => p.source !== null)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map((p) => {
    const dir = dirname(p.manifest_path)
    const files = readdirSync(dir)
      .filter((f) => LICENSE_FILE.test(f) && statSync(join(dir, f)).isFile())
      .sort()
    const spdx = p.license ?? 'see license file'
    const crate = `${p.name} ${p.version}`
    let body = files
      .map((f) => {
        const text = readFileSync(join(dir, f), 'utf8').trim()
        const holder = firstHolder.get(text)
        if (!holder) firstHolder.set(text, `${crate} (${f})`)
        return `### ${f}\n\n${holder ? `Identical to the text of ${holder} above.` : text}`
      })
      .join('\n\n')
    if (!body) {
      const authors = p.authors.length > 0 ? p.authors.join(', ') : 'the crate authors'
      body = `The published crate includes no license file. Licensed under ${spdx}; copyright ${authors}.`
    }
    return `## ${p.name} - ${p.version} (${spdx})\n\n${body}\n`
  })

// The toolchain's own libraries (core, alloc) are linked into every wasm too.
sections.push(
  '## Rust standard library (core, alloc) - toolchain (MIT OR Apache-2.0)\n\n' +
    'Copyright The Rust Project Developers. Licensed under the MIT license or the Apache ' +
    'License 2.0, whose texts are reproduced above.\n',
)

writeFileSync(
  out,
  '# mp-wasm (WebAssembly) crates\n\n' +
    'Generated by mp-wasm/gen-licenses.mjs from mp-wasm/Cargo.lock: the Rust crates compiled into ' +
    'mp_wasm_bg.wasm. Do not edit by hand.\n\n' +
    sections.join('\n'),
)
console.log(`[gen-licenses] ${sections.length} sections → ${out}`)

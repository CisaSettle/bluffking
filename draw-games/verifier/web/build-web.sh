#!/usr/bin/env bash
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../../.." && pwd)"
vendor="${DRAW_WASM_VENDOR_DIR:-$root/client-game/src/vendor/draw-wasm}"
( cd "$here" && wasm-pack build --dev --locked --target web --out-dir target/pkg-web --no-pack )

if [ -n "${DRAW_WASM_VENDOR_DIR:-}" ] || [ -d "$root/client-game" ]; then
  mkdir -p "$vendor"
  cp "$here/target/pkg-web/draw_wasm_bg.wasm" "$vendor/"
  for file in draw_wasm.js draw_wasm.d.ts draw_wasm_bg.wasm.d.ts; do
    {
      printf '// @generated by draw-games/verifier/web/build-web.sh\n'
      cat "$here/target/pkg-web/$file"
    } > "$vendor/$file"
  done
  node "$root/mp-wasm/gen-licenses.mjs" "$vendor/THIRD-PARTY-LICENSES.md" "$here/Cargo.toml"
fi
